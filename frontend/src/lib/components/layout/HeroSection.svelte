<script lang="ts">
	import { formatDate, formatDayOfWeek } from '$lib/services/dateUtils';
	import { formatCount } from '$lib/services/itemDisplay';

	export let date: string;
	export let totalItems: number = 0;
	export let heroImageUrl: string | null = null;
	export let collectionStatus: string = 'success';
	/** Link to the replay for this date. Rendered only when the data actually exists. */
	export let replayUrl: string | null = null;
	/** True while the page is still finding out whether this date has a replay. */
	export let replayPending: boolean = false;
	/** Human-facing name of the LLM that produced THIS day's report (per-day attribution). */
	export let modelDisplayName: string | null = null;
	/** Human-facing name of the model that generated THIS day's hero image. */
	export let imageModelDisplayName: string | null = null;

	$: formattedDate = date ? `${formatDayOfWeek(date)}, ${formatDate(date)}` : '';
	$: hasMeta = totalItems > 0 || !!modelDisplayName || !!imageModelDisplayName;

	// Status indicator color
	$: statusColor =
		collectionStatus === 'success'
			? 'bg-green-500'
			: collectionStatus === 'partial'
				? 'bg-yellow-500'
				: 'bg-red-500';
</script>

<!--
	The image, then a caption bar under it, at every width.

	The caption used to ride over the artwork from tablet up, on a gradient scrim.
	The image is different every day, so no scrim guarantees the small meta line
	is legible, and the caption covered the part of the picture the mascot usually
	stands in. On its own solid bar the line always reads (11.8:1) and the artwork
	is shown whole. The report date is not repeated here: the date navigator
	directly above is the page's heading.
-->
<section class="hero-section" aria-label="Report illustration and run details">
	<div class="hero-frame">
		{#if heroImageUrl}
			<img
				src={heroImageUrl}
				alt="Illustration for the {formattedDate} report: the AATF skunk mascot in a scene drawn from the day's top stories"
				width="1280"
				height="549"
				decoding="async"
				fetchpriority="high"
				class="hero-image"
			/>
		{:else}
			<div
				class="hero-fallback bg-gradient-to-br from-trend-gray-700 to-trend-gray-900 flex items-center justify-center"
			>
				<img src="/assets/logo.webp" alt="" width="96" height="96" class="w-24 h-24 opacity-40" />
			</div>
		{/if}
	</div>

	<div class="hero-caption">
		{#if hasMeta}
			<p class="hero-meta dot-list">
				{#if totalItems > 0}
					<span>{formatCount(totalItems)} items analyzed</span>
				{/if}
				{#if modelDisplayName}
					<span>Content generated by {modelDisplayName}</span>
				{/if}
				{#if imageModelDisplayName}
					<span>Hero image generated by {imageModelDisplayName}</span>
				{/if}
			</p>
		{/if}

		{#if collectionStatus !== 'success' || replayUrl || replayPending}
			<div class="hero-actions">
				{#if collectionStatus !== 'success'}
					<div class="flex items-center gap-2 text-sm text-white">
						<span class={`w-2 h-2 rounded-full ${statusColor}`} aria-hidden="true"></span>
						<span>Collection: {collectionStatus}</span>
					</div>
				{/if}

				{#if replayUrl}
					<a
						class="replay-cta"
						href={replayUrl}
						title="Watch the agents that produced this briefing, replayed against the run's real timestamps"
					>
						<svg class="replay-glyph" viewBox="0 0 12 12" aria-hidden="true">
							<path d="M2.5 1.2v9.6a.6.6 0 0 0 .92.5l7.4-4.8a.6.6 0 0 0 0-1L3.42.7a.6.6 0 0 0-.92.5z" />
						</svg>
						Watch the replay
					</a>
				{/if}
			</div>
		{/if}
	</div>
</section>

